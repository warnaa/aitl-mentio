import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// docs/design-system.md carries the same component table as Start here and Components. This script
// writes it from storybook/design-system/inventory.ts between two markers; `--check` fails when stale.
export const START = "<!-- components:start (generated by npm run docs:agent) -->";
export const END = "<!-- components:end -->";

const cell = (text) => text.replace(/\|/g, "\\|");

/** The markdown table for agents: component, import, when, when not. */
export function componentTable(entries) {
  const rows = entries.map((entry) => `| ${entry.name} | \`${cell(entry.importLine)}\` | ${cell(entry.when)} | ${cell(entry.whenNot)} |`);
  return ["| Component | Import | Use when | Do not use when |", "|---|---|---|---|", ...rows].join("\n");
}

/** Replace the generated block; the markers must exist once, in order. */
export function syncComponents(markdown, entries) {
  const start = markdown.indexOf(START);
  const end = markdown.indexOf(END);
  if (start === -1 || end < start) throw new Error("docs/design-system.md: component table markers are missing");
  return `${markdown.slice(0, start + START.length)}\n${componentTable(entries)}\n${markdown.slice(end)}`;
}

/** Injectable paths and output keep the command testable. */
export async function runAgentDoc({ docPath, entries, check, write }) {
  const current = await readFile(docPath, "utf8");
  const next = syncComponents(current, entries);
  if (check) {
    write(next === current ? "Agent reference is up to date." : "Agent reference is stale: run npm run docs:agent.");
    return next === current ? 0 : 1;
  }
  await writeFile(docPath, next);
  write("Agent reference updated.");
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const { inventory } = await import(pathToFileURL(resolve(packageRoot, "storybook/design-system/inventory.ts")).href);
  process.exitCode = await runAgentDoc({
    docPath: resolve(packageRoot, "../../docs/design-system.md"),
    entries: inventory,
    check: process.argv.includes("--check"),
    write: (line) => process.stdout.write(`${line}\n`),
  });
}
